let x = 10;
x += 5;
console.log(x);//here it will print like (10+5=15) x=15

x -= 3;
console.log(x);//here it will print like (15-3=12) x=12

x *= 3;
console.log(x);//here it will print like (12*3=36) x=36

x /= 18;
console.log(x);//here it will print like (36/18=2) x=2

x %= 2;
console.log(x);//here it will print like (2%2=0) x=0